class Command(BaseCommand):
    help = "Create or update demonstration tags and news articles."

    @transaction.atomic
    def handle(self, *args, **options):
        user_model = get_user_model()
        editor, editor_created = user_model.objects.get_or_create(
            username="demo-editor",
            defaults={
                "email": "demo-editor@example.com",
                "first_name": "Демо",
                "last_name": "Редакція",
            },
        )
        if editor_created:
            editor.set_unusable_password()
            editor.save(update_fields=["password"])

        tags_by_slug = {}
        for name, slug in TAG_DATA:
            tag, _ = Tag.objects.update_or_create(
                slug=slug,
                defaults={"name": name},
            )
            tags_by_slug[slug] = tag

        created_count = 0
        updated_count = 0
        published_at = timezone.now()

        for days_ago, data in enumerate(ARTICLE_DATA):
            article, created = Article.objects.update_or_create(
                slug=data["slug"],
                defaults={
                    "title": data["title"],
                    "body": data["body"],
                    "image": ARTICLE_IMAGE_PATHS[
                        days_ago % len(ARTICLE_IMAGE_PATHS)
                    ],
                    "author": editor,
                    "content_type": data.get("content_type", "news"),
                    "status": Article.Status.PUBLISHED,
                    "access_level": data.get("access", "public"),
                    "published_at": published_at - timedelta(days=days_ago),
                },
            )
            article.tags.set(
                tags_by_slug[tag_slug]
                for tag_slug in data["tags"]
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Demo news ready: {created_count} created, "
                f"{updated_count} updated, {len(TAG_DATA)} tags."
            )
        )
